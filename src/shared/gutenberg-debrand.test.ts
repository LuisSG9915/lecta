async function makeEpub(files: Record<string, string>): Promise<Uint8Array> {
  const writer = new ZipWriter(new BlobWriter("application/epub+zip"));
  await writer.add("mimetype", new TextReader("application/epub+zip"), { level: 0 });
  for (const [name, text] of Object.entries(files)) {
    await writer.add(name, new TextReader(text));
  }
  return new Uint8Array(await (await writer.close()).arrayBuffer());
}

async function readEpub(bytes: Uint8Array): Promise<Map<string, string>> {
  const reader = new ZipReader(new Uint8ArrayReader(bytes));
  const out = new Map<string, string>();
  for (const entry of await reader.getEntries()) {
    if (!entry.directory) out.set(entry.filename, await entry.getData(new TextWriter()));
  }
  await reader.close();
  return out;
}

const fixture = () =>
  makeEpub({
    "META-INF/container.xml": "<container/>",
    "OEBPS/content.opf": OPF,
    "OEBPS/toc.ncx": NCX,
    "OEBPS/0.css": CSS,
    "OEBPS/text-0.xhtml": doc(
      `${HEADER}<h2 id="cap1">I</h2><p class="cap">Se puso el sol. Tras el breve crepúsculo vino tranquila y oscura la noche.</p>`,
    ),
    "OEBPS/text-1.xhtml": doc(FOOTER),
  });

describe("GUTENBERG_MARK", () => {
  it("reconoce la marca y el dominio, no al inventor", () => {
    expect(GUTENBERG_MARK.test("The Project Gutenberg eBook of")).toBe(true);
    expect(GUTENBERG_MARK.test("Project Gutenberg-tm")).toBe(true);
    expect(GUTENBERG_MARK.test("https://www.gutenberg.org/ebooks/46")).toBe(true);
    expect(GUTENBERG_MARK.test("su biblia de Gutenberg, el incunable")).toBe(false);
  });
});

describe("debrandXhtml", () => {
  it("quita cabecera, generator, título con la marca y deja el texto", () => {
    const out = debrandXhtml(doc(`${HEADER}<p>Se puso el sol.</p>`), "Marianela");
    expect(out).not.toMatch(GUTENBERG_MARK);
    expect(out).toContain("<title>Marianela</title>");
    expect(out).toContain("<p>Se puso el sol.</p>");
  });

  it("quita notas sueltas con la marca y deja el texto de los enlaces a gutenberg.org", () => {
    const out = debrandXhtml(
      doc(
        `<h4>There are several editions of this ebook in the Project Gutenberg collection.</h4>` +
          `<p>Ver <a href="https://www.gutenberg.org/ebooks/46">la edición 46</a>.</p>` +
          `<p>¡Maldito Gutenberg! ¿Qué genio maléfico te inspiró?</p>`,
        "A Christmas Carol",
      ),
    );
    expect(out).not.toMatch(GUTENBERG_MARK);
    expect(out).toContain("<p>Ver la edición 46.</p>");
    expect(out).toContain("¡Maldito Gutenberg!");
  });
});

describe("debrandCss", () => {
  it("quita solo las reglas cuyo selector nombra a Gutenberg", () => {
    const out = debrandCss(CSS);
    expect(out).not.toMatch(/gutenberg/i);
    expect(out).toContain("body { margin: 0 }");
    expect(out).toContain("p.cap { text-indent: 1em }");
  });
});

describe("debrandGutenbergEpub", () => {
  it("deja el EPUB sin la marca y sin el documento que solo llevaba la licencia", async () => {
    const { bytes, residual } = await debrandGutenbergEpub(await fixture(), "marianela");
    expect(residual).toEqual([]);
    const files = await readEpub(bytes);
    expect([...files.keys()][0]).toBe("mimetype");
    expect(files.has("OEBPS/text-1.xhtml")).toBe(false);
    for (const [name, text] of files) {
      expect(`${name}: ${text}`).not.toMatch(GUTENBERG_MARK);
    }
    const opf = files.get("OEBPS/content.opf")!;
    expect(opf).toContain("urn:lecta:catalog:marianela");
    expect(opf).toContain("<dc:rights>Public domain in the USA.</dc:rights>");
    expect(opf).not.toContain("text-1.xhtml");
    expect(opf).not.toContain('idref="item5"');
    expect(opf).toContain('idref="pg-header"');
    const ncx = files.get("OEBPS/toc.ncx")!;
    expect(ncx).toContain("Capítulo I");
    expect(ncx).not.toContain("pg-footer");
    expect(ncx).toContain("urn:lecta:catalog:marianela");
    expect(files.get("OEBPS/text-0.xhtml")).toContain("Se puso el sol.");
  });

  it("conserva un documento que ya venía vacío (anclas de página)", async () => {
    const epub = await makeEpub({
      "OEBPS/content.opf": OPF,
      "OEBPS/text-0.xhtml": doc('<p><span id="Page_7" title="[Pg 7]"></span></p>', "Portadilla"),
    });
    const files = await readEpub((await debrandGutenbergEpub(epub, "fray-mocho")).bytes);
    expect(files.get("OEBPS/text-0.xhtml")).toContain('id="Page_7"');
    expect(files.get("OEBPS/content.opf")).toContain('href="text-0.xhtml"');
  });

  it("reporta las menciones sueltas de Gutenberg sin tocarlas", async () => {
    const epub = await makeEpub({
      "OEBPS/content.opf": OPF.replace(/<dc:source>[^]*?<\/dc:publisher>/, ""),
      "OEBPS/text-0.xhtml": doc("<p>En esta mazmorra de Gutenberg fue metido Mariano.</p>", "La desheredada"),
    });
    const { bytes, residual } = await debrandGutenbergEpub(epub, "desheredada");
    expect(residual).toEqual([{ file: "OEBPS/text-0.xhtml", where: "mention" }]);
    expect((await readEpub(bytes)).get("OEBPS/text-0.xhtml")).toContain("mazmorra de Gutenberg");
  });
});
